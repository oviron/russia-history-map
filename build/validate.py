def in_ranges(y, ranges):
    return any(a <= y <= b for a, b in ranges)


def blocks(years):
    out = []
    for y in years:
        if out and out[-1][-1] == y - 1:
            out[-1].append(y)
        else:
            out.append([y])
    return out


def compress(years):
    out = []
    for y in years:
        if out and out[-1][1] == y - 1:
            out[-1][1] = y
        else:
            out.append([y, y])
    return ', '.join(f'{a}' if a == b else f'{a}–{b}' for a, b in out)


